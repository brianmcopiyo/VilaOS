static const uint8_t *glyph12(char ch)
{
    unsigned c = (unsigned char)ch;
    if (c < 32 || c > 126)
        c = '?';
    return font8x12[c - 32];
}

static void expand16(const uint8_t *src12, uint8_t out16[16])
{
    out16[0] = 0;
    out16[1] = src12[1];
    out16[2] = src12[2];
    out16[3] = src12[3];
    out16[4] = src12[4];
    out16[5] = src12[5];
    out16[6] = src12[6];
    out16[7] = src12[7];
    out16[8] = src12[8];
    out16[9] = src12[8];
    out16[10] = src12[9];
    out16[11] = src12[9];
    out16[12] = src12[10];
    out16[13] = src12[10];
    out16[14] = src12[11];
    out16[15] = 0;
}

int font_char_w(FontId id)
{
    (void)id;
    return 8;
}

int font_char_h(FontId id)
{
    return id == FONT_8X16 ? 16 : 12;
}

int font_char_w_scaled(Gfx *g, FontId id)
{
    int s = (g && g->font_scale > 0) ? g->font_scale : 1;
    return font_char_w(id) * s;
}

int font_char_h_scaled(Gfx *g, FontId id)
{
    int s = (g && g->font_scale > 0) ? g->font_scale : 1;
    return font_char_h(id) * s;
}

void font_draw_char(Gfx *g, FontId id, int x, int y, char ch, uint16_t fg, uint16_t bg, int opaque)
{
    const uint8_t *rows = glyph12(ch);
    uint8_t tmp[16];
    int h = 12;
    int s = (g && g->font_scale > 0) ? g->font_scale : 1;
    if (id == FONT_8X16) {
        expand16(rows, tmp);
        rows = tmp;
        h = 16;
    }
    for (int row = 0; row < h; row++) {
        uint8_t bits = rows[row];
        for (int col = 0; col < 8; col++) {
            int on = bits & (0x80 >> col);
            if (!on && !opaque)
                continue;
            uint16_t c = on ? fg : bg;
            if (s <= 1)
                draw_pixel(g, x + col, y + row, c);
            else
                draw_fill(g, x + col * s, y + row * s, s, s, c);
        }
    }
    if (s <= 1)
        gfx_dirty(g, x, y, 8, h);
}

void font_draw_text(Gfx *g, FontId id, int x, int y, const char *text, uint16_t fg, uint16_t bg, int opaque)
{
    if (!text)
        return;
    int cw = font_char_w_scaled(g, id);
    int cx = x;
    while (*text) {
        unsigned char c = (unsigned char)*text;
        if (c >= 0xC0) {
            font_draw_char(g, id, cx, y, '?', fg, bg, opaque);
            if ((c & 0xE0) == 0xC0)
                text += 2;
            else if ((c & 0xF0) == 0xE0)
                text += 3;
            else if ((c & 0xF8) == 0xF0)
                text += 4;
            else
                text++;
            cx += cw;
            continue;
        }
        font_draw_char(g, id, cx, y, (char)c, fg, bg, opaque);
        cx += cw;
        text++;
    }
}

void font_draw_text_clip(Gfx *g, FontId id, int x, int y, int max_w, const char *text, uint16_t fg, uint16_t bg, int opaque)
{
    int cw = font_char_w_scaled(g, id);
    if (!text || max_w < cw)
        return;
    int cx = x;
    int max_x = x + max_w;
    while (*text && cx + cw <= max_x) {
        unsigned char c = (unsigned char)*text;
        if (c >= 0xC0) {
            font_draw_char(g, id, cx, y, '?', fg, bg, opaque);
            if ((c & 0xE0) == 0xC0)
                text += 2;
            else if ((c & 0xF0) == 0xE0)
                text += 3;
            else if ((c & 0xF8) == 0xF0)
                text += 4;
            else
                text++;
            cx += cw;
            continue;
        }
        font_draw_char(g, id, cx, y, (char)c, fg, bg, opaque);
        cx += cw;
        text++;
    }
}

int font_text_w(FontId id, const char *text)
{
    (void)id;
    int n = 0;
    if (!text)
        return 0;
    while (*text) {
        unsigned char c = (unsigned char)*text;
        if (c >= 0xC0) {
            if ((c & 0xE0) == 0xC0)
                text += 2;
            else if ((c & 0xF0) == 0xE0)
                text += 3;
            else if ((c & 0xF8) == 0xF0)
                text += 4;
            else
                text++;
            n++;
            continue;
        }
        text++;
        n++;
    }
    return n * 8;
}

int font_text_w_scaled(Gfx *g, FontId id, const char *text)
{
    int s = (g && g->font_scale > 0) ? g->font_scale : 1;
    return font_text_w(id, text) * s;
}
